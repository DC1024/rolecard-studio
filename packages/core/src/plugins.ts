import { readdir, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import {
  DeclarativePluginManifestSchema,
  type DeclarativePluginManifest,
  type RoleCardContent,
} from '@rolecard/shared';
import { type CoreError, type Result, err, ok } from './types.js';

export function validatePluginManifest(
  raw: unknown,
): Result<DeclarativePluginManifest, CoreError> {
  const parsed = DeclarativePluginManifestSchema.safeParse(raw);
  if (!parsed.success) {
    return err({
      code: 'INVALID_PLUGIN_MANIFEST',
      message: `插件清单校验失败：${parsed.error.issues[0]?.message ?? '格式错误'}`,
      status: 400,
    });
  }

  const manifest = parsed.data;
  if (manifest.type === 'template' && !manifest.templateSpec) {
    return err({
      code: 'MISSING_TEMPLATE_SPEC',
      message: 'template 类型插件必须提供 templateSpec',
      status: 400,
    });
  }
  if (manifest.type === 'export_formatter' && !manifest.exportSpec) {
    return err({
      code: 'MISSING_EXPORT_SPEC',
      message: 'export_formatter 类型插件必须提供 exportSpec',
      status: 400,
    });
  }
  if (manifest.type === 'search_source' && !manifest.searchSpec) {
    return err({
      code: 'MISSING_SEARCH_SPEC',
      message: 'search_source 类型插件必须提供 searchSpec',
      status: 400,
    });
  }

  return ok(manifest);
}

export function renderDeclarativeExport(
  manifest: DeclarativePluginManifest,
  card: RoleCardContent,
  meta: { workName?: string; version?: number; mode?: string } = {},
): Result<{ filename: string; mimeType: string; content: string }, CoreError> {
  if (manifest.type !== 'export_formatter' || !manifest.exportSpec) {
    return err({
      code: 'NOT_EXPORT_PLUGIN',
      message: `插件 ${manifest.id} 不是导出格式器插件`,
      status: 400,
    });
  }

  const variables: Record<string, string> = {
    name: card.name,
    workName: meta.workName ?? '',
    version: String(meta.version ?? 1),
    mode: meta.mode ?? 'A',
    summary: card.summary,
    personality: card.personality,
    appearance: card.appearance,
    background: card.background,
    scenario: card.scenario,
    first_mes: card.first_mes,
    mes_example: card.mes_example,
    system_prompt: card.system_prompt,
    creator_notes: card.creator_notes,
    tags: card.tags.join(', '),
    json: JSON.stringify(card, null, 2),
  };

  // Safe string-only placeholder interpolation without code evaluation
  const rendered = manifest.exportSpec.template.replace(/\{\{([a-zA-Z0-9_]+)\}\}/g, (_, key: string) => {
    return variables[key] ?? '';
  });

  const safeName = card.name.replace(/[\\/:*?"<>|\r\n]+/g, '_').trim() || 'rolecard';
  return ok({
    filename: `${safeName}.${manifest.exportSpec.fileExtension}`,
    mimeType: manifest.exportSpec.mimeType,
    content: rendered,
  });
}

