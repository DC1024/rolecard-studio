export async function loadPluginsFromDirectory(
  dirPath: string,
): Promise<DeclarativePluginManifest[]> {
  const builtins = getBuiltinDeclarativePlugins();
  if (!existsSync(dirPath)) {
    return builtins;
  }

  const loaded = new Map<string, DeclarativePluginManifest>(builtins.map((p) => [p.id, p]));
  const entries = await readdir(dirPath, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.json')) continue;
    try {
      const raw = JSON.parse(await readFile(join(dirPath, entry.name), 'utf8')) as unknown;
      const valid = validatePluginManifest(raw);
      if (valid.ok) {
        loaded.set(valid.value.id, valid.value);
      }
    } catch {
      // skip invalid third-party manifest without crashing server
    }
  }

  return Array.from(loaded.values());
}
